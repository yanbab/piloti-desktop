import type { DesktopSettings } from "@/core/config/desktop-settings";
import type { SettingValue } from "@/core/ports/settings";
import { GVARIANT_TYPE, toGVariant } from "./gvariant";
import type { DesktopKeyKind } from "./piloti-settings-ini";

/** dconf path of a Piloti schema: `org.piloti.desktop.dock` → `/org/piloti/desktop/dock/`. */
export function schemaPath(schema: string): string {
  return `/${schema.split(".").join("/")}/`;
}

const xmlEscape = (s: string) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function asText(value: SettingValue | undefined, kind: DesktopKeyKind): string {
  if (value === undefined) return kind === "boolean" ? "false" : kind === "number" ? "0" : "";
  return Array.isArray(value) ? value.join(";") : String(value);
}

/**
 * The `.gschema.xml` for Piloti's desktop schemas, from the same table as
 * settings.ini (`desktopSchemaKeys`) and the shell's defaults.
 */
export function buildPilotiGschemaXml(
  keys: ReadonlyArray<{ schema: string; key: string; kind: DesktopKeyKind }>,
  defaults: Record<string, Record<string, SettingValue>>,
): string {
  const bySchema = new Map<string, Array<{ key: string; kind: DesktopKeyKind }>>();
  for (const { schema, key, kind } of keys) {
    if (!bySchema.has(schema)) bySchema.set(schema, []);
    bySchema.get(schema)!.push({ key, kind });
  }
  const out = ['<?xml version="1.0" encoding="UTF-8"?>', "<!-- Generated by scripts/generate-gschemas.ts; do not edit. -->", "<schemalist>"];
  for (const [schema, entries] of bySchema) {
    out.push(`  <schema id="${schema}" path="${schemaPath(schema)}">`);
    for (const { key, kind } of entries) {
      const def = toGVariant(asText(defaults[schema]?.[key], kind), kind);
      out.push(`    <key name="${key}" type="${GVARIANT_TYPE[kind]}">`);
      out.push(`      <default>${xmlEscape(def)}</default>`);
      out.push("    </key>");
    }
    out.push("  </schema>");
  }
  out.push("</schemalist>", "");
  return out.join("\n");
}

/**
 * The defaults written in the schema, from the shell's own. Piloti only reads
 * back what was set (`dconf dump`), so these are for `gsettings` and
 * dconf-editor; ones that depend on where the generator runs are fixed: Linux,
 * and the dock's apps (from the app catalog at run time) left empty.
 */
export function gschemaDefaults(defaults: DesktopSettings): DesktopSettings {
  return { ...defaults, computerModel: "pc", pinnedAppIds: [] };
}

export const PILOTI_GSCHEMA_FILE = "data/files/usr/share/glib-2.0/schemas/org.piloti.desktop.gschema.xml";
